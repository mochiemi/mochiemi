              <h2>Como o cerume é removido</h2>
            </div>
          </header>

          <p>
            O cerume é feito de secreções sebáceas ricas em ácidos graxos livres, triglicerídeos,
            colesterol e escamas de queratina. O carbonato de sódio, sal alcalino, promove
            <strong>saponificação parcial</strong> desses ácidos:
          </p>

          <p class="equation">
            Ácido graxo do cerume + Na₂CO₃ → sabão de sódio solúvel + H₂O + CO₂ ↑
          </p>

          <p>
            Os sabões formados são tensoativos autógenos: emulsificam os lipídeos e desintegram a
            massa endurecida. As microbolhas de CO₂ ainda acrescentam fragmentação mecânica.
          </p>

